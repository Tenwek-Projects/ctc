/**
 * One-off / maintenance: emit SVG path elements for African countries from Natural Earth 110m.
 * Run: node scripts/generate-africa-country-paths.cjs
 */
const fs = require('fs');
const path = require('path');
const topojson = require('topojson-client');
const d3 = require('d3-geo');

const topology = JSON.parse(
    fs.readFileSync(path.join(__dirname, '../node_modules/world-atlas/countries-110m.json'), 'utf8'),
);
const countries = topojson.feature(topology, topology.objects.countries);

// Match viewBox used in home-impact-africa-map (520 x 580) — tuned to prior Bomet position (~398, 304)
const projection = d3
    .geoMercator()
    .rotate([0, 0])
    .center([17, 2])
    .scale(330)
    .translate([259, 289]);

const geoPath = d3.geoPath(projection);

const excludeNames = new Set([
    'Yemen',
    'Saudi Arabia',
    'Oman',
    'United Arab Emirates',
    'Qatar',
    'Kuwait',
    'Iraq',
    'Iran',
    'Israel',
    'Jordan',
    'Lebanon',
    'Syria',
    'Turkey',
    'Cyprus',
    'Palestine',
    'Georgia',
    'Armenia',
    'Azerbaijan',
    'Spain',
    'Portugal',
    'France',
    'Italy',
    'Greece',
    'Malta',
]);

function includeFeature(feat) {
    const name = feat.properties.name;
    if (excludeNames.has(name)) return false;
    const [lon, lat] = d3.geoCentroid(feat);
    if (lon < -25 || lon > 55 || lat < -37 || lat > 38) return false;
    // Clip Middle East / southern Europe stragglers
    if (lon > 40 && lat > 28) return false;
    if (lon < -8 && lat > 35) return false;
    return true;
}

const lines = ['{{-- Generated by scripts/generate-africa-country-paths.cjs; do not edit by hand. --}}'];
for (const feat of countries.features) {
    if (!includeFeature(feat)) continue;
    const d = geoPath(feat);
    if (!d) continue;
    const safeName = String(feat.properties.name).replace(/&/g, '&amp;').replace(/"/g, '&quot;');
    lines.push(`<path class="ctc-impact-country" d="${d}" data-country="${safeName}" />`);
}

const out = path.join(__dirname, '../resources/views/components/partials/africa-country-paths.blade.php');
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, lines.join('\n') + '\n', 'utf8');
console.log('Wrote', out, 'paths:', lines.length - 1);
